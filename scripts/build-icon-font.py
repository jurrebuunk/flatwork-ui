#!/usr/bin/env python3
"""Builds the flatwork-saas icon font from Google's Material Symbols.

The upstream variable font carries every axis (5.4 MB). flatwork-saas uses
the Rounded style at weight 400, grade 0, optical size 20, so those axes are
pinned; FILL stays variable for filled/active icons. Result: ~560 KB.

Also writes the TypeScript union of every icon name for packages/react.

    npm pack material-symbols@0.49.0 && tar xzf material-symbols-0.49.0.tgz
    nix shell --impure --expr '(import (builtins.getFlake "nixpkgs") {}).python3.withPackages (p: [ p.fonttools p.brotli ])' \
      -c python3 scripts/build-icon-font.py package/

Material Symbols is Apache-2.0 licensed (Google).
"""
import re
import sys
from pathlib import Path

from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

root = Path(__file__).resolve().parent.parent
src = Path(sys.argv[1])

font = TTFont(src / "material-symbols-rounded.woff2")
instantiateVariableFont(font, {"wght": 400, "GRAD": 0, "opsz": 20}, inplace=True)
font.flavor = "woff2"
out = root / "themes/flatwork-saas/fonts/material-symbols-rounded.woff2"
font.save(out)
print(f"wrote {out} ({out.stat().st_size // 1024} KB)")

names = re.findall(r'^\s*"([a-z0-9_]+)",?$', (src / "index.d.ts").read_text(), re.M)
version = re.search(r'"version":\s*"([^"]+)"', (src / "package.json").read_text()).group(1)
ts = root / "packages/react/src/icon-names.ts"
ts.write_text(
    f"// Generated by scripts/build-icon-font.py from material-symbols@{version} — do not edit.\n"
    "/** Every Material Symbols icon name. Browse them at https://fonts.google.com/icons */\n"
    "export type IconName =\n" + "\n".join(f'  | "{n}"' for n in names) + ";\n"
)
print(f"wrote {ts} ({len(names)} names)")
